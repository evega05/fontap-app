const IdiomaContext = createContext({ idioma: 'es', cambiarIdioma: () => {}, t: (k) => k });

export function IdiomaProvider({ children }) {
  const [idioma, setIdioma] = useState('es');

  useEffect(() => {
    AsyncStorage.getItem('idioma').then((v) => {
      if (v && traducciones[v]) setIdioma(v);
    }).catch(() => {});
  }, []);

  const cambiarIdioma = (codigo) => {
    if (!traducciones[codigo]) return;
    setIdioma(codigo);
    AsyncStorage.setItem('idioma', codigo).catch(() => {});
  };

  const t = (clave) => traducciones[idioma]?.[clave] ?? traducciones.es[clave] ?? clave;

  return (
    <IdiomaContext.Provider value={{ idioma, cambiarIdioma, t }}>
      {children}
    </IdiomaContext.Provider>
  );
}

export const useIdioma = () => useContext(IdiomaContext);
